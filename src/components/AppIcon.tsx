const SEMANTIC_COLORS: Record<string, string> = {
  "dot-green": "text-emerald-500 fill-emerald-500",
  "dot-amber": "text-amber-400 fill-amber-400",
  "dot-red": "text-rose-500 fill-rose-500",
};

function stripVariationSelector(value: string): string {
  return value.replace(/\uFE0F/g, "").trim();
}

export function resolveIconEntry(name?: string | null): { component: LucideIcon; colorClass?: string } {
  if (!name) return { component: Circle };
  const cleaned = stripVariationSelector(name);

  if (ICON_MAP[cleaned]) {
    return {
      component: ICON_MAP[cleaned],
      colorClass: SEMANTIC_COLORS[cleaned],
    };
  }

  if (EMOJI_MAP[cleaned]) {
    return EMOJI_MAP[cleaned];
  }

  return { component: Package };
}

export interface AppIconProps {
  icon?: string | null;
  name?: string | null;
  className?: string;
  strokeWidth?: number;
}

export function AppIcon({
  icon,
  name,
  className = "w-4 h-4",
  strokeWidth = 2,
}: AppIconProps) {
  const key = name ?? icon;
  const { component: IconComponent, colorClass } = resolveIconEntry(key);
  const finalClass = colorClass ? `${className} ${colorClass}` : className;
  return <IconComponent className={finalClass} strokeWidth={strokeWidth} aria-hidden="true" />;
}

export function StatusDot({ color = "green", className = "" }: { color?: "green" | "amber" | "red" | "blue" | "slate"; className?: string }) {
  const colorClasses: Record<string, string> = {
    green: "bg-emerald-500",
    amber: "bg-amber-400",
    red: "bg-rose-500",
    blue: "bg-blue-500",
    slate: "bg-slate-400",
  };
  return <span className={`inline-block h-2.5 w-2.5 shrink-0 rounded-full ${colorClasses[color] || colorClasses.slate} ${className}`} aria-hidden="true" />;
}
