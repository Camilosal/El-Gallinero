import { db } from "@/db";
import { catalogos, farmLocations, feedInventory, feedMovements } from "@/db/schema";
import { and, eq, gte, lte, sql } from "drizzle-orm";
import { NextRequest, NextResponse } from "next/server";
import { withApiHandler } from "@/lib/api-handler";
import { isDateOnly } from "@/lib/date-validation";
import { getStageSpecies } from "@/lib/feeding/stage-species";
import { normalizeFeedingSpecies } from "@/lib/species";

export const dynamic = "force-dynamic";

type Row = {
  species: string;
  locationId: string | null;
  locationName: string;
  kg: number;
  cost: number;
  programCost: number;
  animalDays: number;
  costPerAnimalDay: number | null;
};

const money = (n: number) => Math.round(n * 100) / 100;
const NO_SPECIES = "sin_especie";

/**
 * GET /api/analisis/reportes/costos-alimento?from&to&species&locationId
 * Costo del alimento consumido por especie y lugar. Usa el costo unitario
 * congelado en cada movimiento (`unit_cost`) y, para registros anteriores,
 * el costo actual del inventario. Es una vista de consumo (devengado) y no
 * reemplaza los egresos de compra de `transactions`.
 */
export const GET = withApiHandler(async (req: NextRequest) => {
  const { searchParams } = new URL(req.url);
  const today = new Date().toISOString().slice(0, 10);
  const from = searchParams.get("from") || `${today.slice(0, 4)}-01-01`;
  const to = searchParams.get("to") || today;
  if (!isDateOnly(from) || !isDateOnly(to) || from > to) {
    return NextResponse.json({ error: "Rango de fechas inválido" }, { status: 400 });
  }
  const speciesParam = searchParams.get("species");
  const speciesFilter = speciesParam ? normalizeFeedingSpecies(speciesParam) : null;
  if (speciesParam && !speciesFilter) return NextResponse.json({ error: "Especie no válida" }, { status: 400 });
  const locationFilter = searchParams.get("locationId");

  const conditions = [
    eq(feedMovements.isEntry, false),
    gte(feedMovements.date, from),
    lte(feedMovements.date, to),
  ];
  if (locationFilter) conditions.push(eq(feedMovements.locationId, locationFilter));

  const unitCost = sql`coalesce(${feedMovements.unitCost}, ${feedInventory.costPerUnit})::numeric`;
  const grouped = await db
    .select({
      movementSpecies: feedMovements.species,
      stageType: catalogos.tipo,
      stageName: catalogos.value,
      locationId: feedMovements.locationId,
      locationName: farmLocations.name,
      kg: sql<string>`coalesce(sum(${feedMovements.quantity}::numeric), 0)`,
      cost: sql<string>`coalesce(sum(${feedMovements.quantity}::numeric * ${unitCost}), 0)`,
      programCost: sql<string>`coalesce(sum(case when ${feedMovements.autoGenerated} then ${feedMovements.quantity}::numeric * ${unitCost} else 0 end), 0)`,
    })
    .from(feedMovements)
    .innerJoin(feedInventory, eq(feedMovements.feedId, feedInventory.id))
    .leftJoin(catalogos, eq(feedMovements.stageCatalogoId, catalogos.id))
    .leftJoin(farmLocations, eq(feedMovements.locationId, farmLocations.id))
    .where(and(...conditions))
    .groupBy(feedMovements.species, catalogos.tipo, catalogos.value, feedMovements.locationId, farmLocations.name);

  // Animales-día: un grupo por día, etapa y lugar (se repite por cada alimento del programa).
  const groups = await db
    .selectDistinct({
      date: feedMovements.date,
      stageId: feedMovements.stageCatalogoId,
      locationId: feedMovements.locationId,
      henCount: feedMovements.henCount,
      movementSpecies: feedMovements.species,
      stageType: catalogos.tipo,
      stageName: catalogos.value,
    })
    .from(feedMovements)
    .leftJoin(catalogos, eq(feedMovements.stageCatalogoId, catalogos.id))
    .where(and(...conditions, eq(feedMovements.autoGenerated, true)));

  const resolveSpecies = (movementSpecies: string | null, stageType: string | null, stageName: string | null): string => {
    if (movementSpecies) return movementSpecies;
    if (stageName !== null || stageType !== null) return getStageSpecies({ tipo: stageType, value: stageName });
    return NO_SPECIES;
  };

  const rows = new Map<string, Row>();
  const keyOf = (species: string, locationId: string | null) => `${species}|${locationId ?? ""}`;
  for (const g of grouped) {
    const species = resolveSpecies(g.movementSpecies, g.stageType, g.stageName);
    const key = keyOf(species, g.locationId);
    const row = rows.get(key) ?? {
      species, locationId: g.locationId, locationName: g.locationName ?? "Sin lugar",
      kg: 0, cost: 0, programCost: 0, animalDays: 0, costPerAnimalDay: null,
    };
    row.kg += Number(g.kg);
    row.cost += Number(g.cost);
    row.programCost += Number(g.programCost);
    rows.set(key, row);
  }
  for (const g of groups) {
    const species = resolveSpecies(g.movementSpecies, g.stageType, g.stageName);
    const row = rows.get(keyOf(species, g.locationId));
    if (row) row.animalDays += g.henCount ?? 0;
  }

  let result = Array.from(rows.values());
  if (speciesFilter) result = result.filter((row) => row.species === speciesFilter);
  for (const row of result) {
    row.kg = money(row.kg);
    row.cost = money(row.cost);
    row.costPerAnimalDay = row.animalDays > 0 ? Math.round((row.programCost / row.animalDays) * 10000) / 10000 : null;
    row.programCost = money(row.programCost);
  }
  result.sort((a, b) => b.cost - a.cost);

  const rollup = (select: (row: Row) => string) => {
    const map = new Map<string, { key: string; kg: number; cost: number }>();
    for (const row of result) {
      const key = select(row);
      const entry = map.get(key) ?? { key, kg: 0, cost: 0 };
      entry.kg += row.kg;
      entry.cost += row.cost;
      map.set(key, entry);
    }
    return Array.from(map.values()).map((e) => ({ ...e, kg: money(e.kg), cost: money(e.cost) })).sort((a, b) => b.cost - a.cost);
  };

  return NextResponse.json({
    from,
    to,
    rows: result,
    bySpecies: rollup((row) => row.species),
    byLocation: rollup((row) => row.locationName),
    totalKg: money(result.reduce((s, r) => s + r.kg, 0)),
    totalCost: money(result.reduce((s, r) => s + r.cost, 0)),
  });
});

