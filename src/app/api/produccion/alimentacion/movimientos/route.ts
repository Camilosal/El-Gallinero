import { db } from "@/db";
import { feedMovements, feedInventory, transactions, catalogos, farmLocations } from "@/db/schema";
import { eq, desc, sql } from "drizzle-orm";
import { NextRequest, NextResponse } from "next/server";
import { runFeedProgramCatchup } from "@/lib/feeding/runProgram";
import { withApiHandler, safeParseJson } from "@/lib/api-handler";
import { deleteFeedMovementAndReverseStock } from "@/lib/financial-records";

export const dynamic = "force-dynamic";

export const GET = withApiHandler(async () => {
  await runFeedProgramCatchup();
  const data = await db
    .select({
      id: feedMovements.id,
      feedId: feedMovements.feedId,
      feedName: feedInventory.name,
      feedUnit: feedInventory.unit,
      quantity: feedMovements.quantity,
      isEntry: feedMovements.isEntry,
      movementType: feedMovements.movementType,
      autoGenerated: feedMovements.autoGenerated,
      stageCatalogoId: feedMovements.stageCatalogoId,
      stageName: catalogos.value,
      henCount: feedMovements.henCount,
      date: feedMovements.date,
      notes: feedMovements.notes,
      locationId: feedMovements.locationId,
      locationName: farmLocations.name,
      createdAt: feedMovements.createdAt,
    })
    .from(feedMovements)
    .leftJoin(feedInventory, eq(feedMovements.feedId, feedInventory.id))
    .leftJoin(catalogos, eq(feedMovements.stageCatalogoId, catalogos.id))
    .leftJoin(farmLocations, eq(feedMovements.locationId, farmLocations.id))
    .orderBy(desc(feedMovements.createdAt))
    .limit(100);
  return NextResponse.json(data);
});

export const POST = withApiHandler(async (req: NextRequest) => {
  const body = await safeParseJson(req);
  if (!body || typeof body !== "object") return NextResponse.json({ error: "Cuerpo inválido" }, { status: 400 });
  const qty = Number(body.quantity);

  if (!Number.isFinite(qty) || qty <= 0) {
    return NextResponse.json({ error: "Cantidad inválida" }, { status: 400 });
  }
  if (typeof body.isEntry !== "boolean") return NextResponse.json({ error: "Tipo de movimiento inválido" }, { status: 400 });
  if (!body.isEntry && !body.locationId) return NextResponse.json({ error: "Selecciona el lugar al que se suministró el alimento" }, { status: 400 });
  if (body.locationId) {
    const [location] = await db.select({ id: farmLocations.id, status: farmLocations.status, operationalStatus: farmLocations.operationalStatus })
      .from(farmLocations).where(eq(farmLocations.id, String(body.locationId)));
    if (!location || location.status !== "activa" || (!body.isEntry && ["restringida", "fuera_servicio"].includes(location.operationalStatus))) {
      return NextResponse.json({ error: "Selecciona un lugar activo y disponible" }, { status: 400 });
    }
  }
  if (typeof body.date !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(body.date) || Number.isNaN(new Date(`${body.date}T00:00:00.000Z`).getTime()) || new Date(`${body.date}T00:00:00.000Z`).toISOString().slice(0, 10) !== body.date) {
    return NextResponse.json({ error: "Fecha inválida" }, { status: 400 });
  }
  if (body.date > new Date().toISOString().slice(0, 10)) {
    return NextResponse.json({ error: "No se pueden registrar movimientos de alimento en una fecha futura" }, { status: 400 });
  }

  // Bring the current inventory up to today before applying a manual movement.
  // Historical movement dates must not rewind or replay the automatic program.
  await runFeedProgramCatchup();

  const created = await db.transaction(async (tx) => {
    // Validate feed inside transaction
    const [feed] = await tx.select().from(feedInventory).where(eq(feedInventory.id, body.feedId)).for("update");
    if (!feed) {
      throw new Error("Alimento no encontrado");
    }

    // Prevent negative stock on consumption — check inside transaction
    if (!body.isEntry && qty > Number(feed.currentStock)) {
      throw new Error(`Stock insuficiente: ${feed.name} solo tiene ${feed.currentStock} ${feed.unit}`);
    }

    const [inserted] = await tx.insert(feedMovements).values({
      feedId: body.feedId,
      quantity: body.quantity,
      isEntry: body.isEntry,
      movementType: body.movementType || (body.isEntry ? "compra" : "consumo_manual"),
      autoGenerated: false,
      stageCatalogoId: body.stageCatalogoId || null,
      henCount: body.henCount || null,
      locationId: body.locationId || null,
      date: body.date,
      notes: body.notes || null,
    }).returning();

    // Update stock with relative SQL (no sql.raw — operator baked into literal)
    await tx.update(feedInventory).set({
      currentStock: body.isEntry
        ? sql`(${feedInventory.currentStock}::numeric + ${qty})`
        : sql`(${feedInventory.currentStock}::numeric - ${qty})`,
      updatedAt: new Date(),
    }).where(eq(feedInventory.id, body.feedId));

    // Purchased (suplementario) feed entry registers an expense in finances
    if (body.isEntry && feed.category === "suplementario" && Number(feed.costPerUnit) > 0) {
      const amount = (qty * Number(feed.costPerUnit)).toFixed(2);
      await tx.insert(transactions).values({
        date: body.date,
        type: "egreso",
        category: "Compra de alimento",
        description: `Compra de ${body.quantity} ${feed.unit} de ${feed.name}`,
        amount,
        quantity: body.quantity,
        unitPrice: feed.costPerUnit,
        unit: feed.unit,
        counterparty: feed.supplier || null,
        sourceType: "alimento",
        sourceId: inserted.id,
      });
    }

    return inserted;
  });

  return NextResponse.json(created, { status: 201 });
});

export const DELETE = withApiHandler(async (req: NextRequest) => {
  const { searchParams } = new URL(req.url);
  const id = searchParams.get("id");
  if (!id) return NextResponse.json({ error: "ID requerido" }, { status: 400 });
  await db.transaction(async (tx) => {
    await deleteFeedMovementAndReverseStock(tx, id);
  });
  return NextResponse.json({ ok: true });
});
