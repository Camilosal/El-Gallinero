import { isDateOnly } from "@/lib/date-validation";
import { db } from "@/db";
import { catalogos, hens, feedPrograms, feedInventory, feedMovements, appSettings } from "@/db/schema";
import { eq, and, sql, or } from "drizzle-orm";

export const dynamic = "force-dynamic";

/** Clave fija para el advisory lock que serializa la ejecución del programa. */
const FEED_PROGRAM_LOCK_KEY = 48221001;
const FEED_PROGRAM_CHECKPOINT_KEY = "feeding.program_checkpoint_date";

function dateStr(d: Date): string {
  return d.toISOString().split("T")[0];
}

function addDays(dateStrValue: string, days: number): string {
  const d = new Date(dateStrValue + "T12:00:00");
  d.setDate(d.getDate() + days);
  return dateStr(d);
}


/**
 * Cuenta gallinas activas por etapa con corte a una fecha concreta.
 * Misma lógica que GET /api/produccion/etapas pero parametrizada por fecha, de modo que
 * la ejecución histórica del programa respete cuántas gallinas había en cada
 * etapa en cada día (según su fecha de nacimiento).
 */
export async function countHensByStageForDate(asOf: Date, client: any = db): Promise<Record<string, number>> {
  const stages = await client
    .select()
    .from(catalogos)
    .where(and(eq(catalogos.category, "etapa_crecimiento"), eq(catalogos.isActive, true)));

  const counts: Record<string, number> = {};
  for (const stage of stages) {
    const minWeeks = stage.minWeeks ?? 0;
    const maxWeeks = stage.maxWeeks;
    const minDate = new Date(asOf);
    minDate.setDate(minDate.getDate() - minWeeks * 7);

    let countResult;
    if (maxWeeks === null) {
      countResult = await client
        .select({ count: sql<number>`count(*)::int` })
        .from(hens)
        .where(
          and(
            sql`${hens.birthDate}::date <= ${dateStr(minDate)}::date`,
            or(eq(hens.status, "activa"), eq(hens.status, "empollando"), eq(hens.status, "recomendada_sacrificio"))
          )
        );
    } else {
      const maxDate = new Date(asOf);
      maxDate.setDate(maxDate.getDate() - maxWeeks * 7);
      countResult = await client
        .select({ count: sql<number>`count(*)::int` })
        .from(hens)
        .where(
          and(
            sql`${hens.birthDate}::date <= ${dateStr(minDate)}::date`,
            sql`${hens.birthDate}::date > ${dateStr(maxDate)}::date`,
            or(eq(hens.status, "activa"), eq(hens.status, "empollando"), eq(hens.status, "recomendada_sacrificio"))
          )
        );
    }
    counts[stage.id] = countResult?.[0]?.count ?? 0;
  }
  return counts;
}

/** Cuenta las aves de cada etapa separadas por su alojamiento actual. */
export async function countHensByStageAndLocationForDate(
  asOf: Date,
  client: any = db,
): Promise<Record<string, { locationId: string | null; count: number }[]>> {
  const stages = await client
    .select()
    .from(catalogos)
    .where(and(eq(catalogos.category, "etapa_crecimiento"), eq(catalogos.isActive, true)));

  const counts: Record<string, { locationId: string | null; count: number }[]> = {};
  for (const stage of stages) {
    const minWeeks = stage.minWeeks ?? 0;
    const maxWeeks = stage.maxWeeks;
    const minDate = new Date(asOf);
    minDate.setDate(minDate.getDate() - minWeeks * 7);
    const conditions = [
      sql`${hens.birthDate}::date <= ${dateStr(minDate)}::date`,
      or(eq(hens.status, "activa"), eq(hens.status, "empollando"), eq(hens.status, "recomendada_sacrificio")),
    ];
    if (maxWeeks !== null) {
      const maxDate = new Date(asOf);
      maxDate.setDate(maxDate.getDate() - maxWeeks * 7);
      conditions.push(sql`${hens.birthDate}::date > ${dateStr(maxDate)}::date`);
    }
    const rows = await client
      .select({ locationId: hens.locationId, count: sql<number>`count(*)::int` })
      .from(hens)
      .where(and(...conditions))
      .groupBy(hens.locationId);
    counts[stage.id] = rows.map((row: { locationId: string | null; count: number }) => ({
      locationId: row.locationId,
      count: Number(row.count),
    }));
  }
  return counts;
}

/**
 * Ejecuta (catch-up) los programas de alimentación hasta la fecha de consulta.
 *
 * El productor NO registra el consumo día a día: los programas por etapa se
 * materializan automáticamente como movimientos de consumo (isEntry=false,
 * autoGenerated=true) y descuentan del inventario. Solo los días posteriores a
 * la última fecha ya materializada se procesan ("solo hacia adelante"), y los
 * datos siempre quedan con corte al día de consulta.
 *
 * Reglas:
 * - Si el consumo automático supera el stock, el stock llega a 0 (nunca negativo).
 * - La ejecución es idempotente y serializada con un advisory lock de PostgreSQL.
 */
export async function runFeedProgramCatchup(asOf?: Date): Promise<void> {
  const requestedDate = dateStr(asOf ?? new Date());
  const todayStr = dateStr(new Date());
  // A catch-up may be requested for an old manual movement date, but it must
  // never materialize future feed consumption.
  const asOfStr = requestedDate > todayStr ? todayStr : requestedDate;

  await db.transaction(async (tx) => {
    await tx.execute(sql`SELECT pg_advisory_xact_lock(${FEED_PROGRAM_LOCK_KEY})`);

    // Use a durable calendar checkpoint as well as the movement ledger. The
    // latter alone cannot advance on days with no stock, causing later runs to
    // replay those days after a new purchase and consume fresh stock retroactively.
    const [checkpointRow] = await tx.select({ value: appSettings.value }).from(appSettings)
      .where(eq(appSettings.key, FEED_PROGRAM_CHECKPOINT_KEY));
    const [lastRow] = await tx
      .select({ lastDate: sql<string>`MAX(${feedMovements.date})` })
      .from(feedMovements)
      .where(and(eq(feedMovements.isEntry, false), eq(feedMovements.autoGenerated, true)));
    const checkpointCandidates = [checkpointRow?.value, lastRow?.lastDate]
      .filter((value): value is string => isDateOnly(value));
    const lastDateStr = checkpointCandidates.sort().at(-1) ?? null;

    // Sin histórico previo: solo materializa desde el día de consulta
    const startStr = lastDateStr ? addDays(lastDateStr, 1) : asOfStr;
    if (startStr > asOfStr) return; // nada pendiente

    // 2. Programas agrupados por etapa y stock actual
    const programs = await tx.select().from(feedPrograms);
    // Hold row locks while calculating and applying consumption so manual
    // movements and purchases cannot overwrite a stale stock snapshot.
    const feeds = await tx.select().from(feedInventory).for("update");
    const programByStage = new Map<string, { feedId: string; gramsPerHen: number }[]>();
    for (const p of programs) {
      if (!programByStage.has(p.stageCatalogoId)) programByStage.set(p.stageCatalogoId, []);
      programByStage.get(p.stageCatalogoId)!.push({ feedId: p.feedId, gramsPerHen: Number(p.dailyAmountPerHen) });
    }
    const stockById = new Map<string, number>();
    for (const f of feeds) stockById.set(f.id, Number(f.currentStock));

    const movementsToInsert: {
      feedId: string;
      quantity: string;
      isEntry: boolean;
      movementType: string;
      autoGenerated: boolean;
      stageCatalogoId: string;
      henCount: number;
      locationId: string | null;
      date: string;
      notes: string;
    }[] = [];

    // 3. Materializar cada día pendiente
    let cur = startStr;
    while (cur <= asOfStr) {
      const dayDate = new Date(cur + "T12:00:00");
      const henCounts = await countHensByStageAndLocationForDate(dayDate, tx);

      for (const [stageId, entries] of programByStage) {
        for (const group of henCounts[stageId] ?? []) {
          if (group.count <= 0) continue;
          for (const e of entries) {
            const kg = (e.gramsPerHen * group.count) / 1000;
            if (kg <= 0) continue;
            movementsToInsert.push({
              feedId: e.feedId,
              quantity: kg.toFixed(2),
              isEntry: false,
              movementType: "consumo_programa",
              autoGenerated: true,
              stageCatalogoId: stageId,
              henCount: group.count,
              locationId: group.locationId,
              date: cur,
              notes: "Consumo automático por programa",
            });
          }
        }
      }
      cur = addDays(cur, 1);
    }

    // Only materialize consumption that can actually be taken from stock.
    // This keeps the movement ledger equal to the stock balance instead of
    // recording more consumed feed than was available.
    const remainingByFeed = new Map(stockById);
    const actualConsumptionByFeed: Record<string, number> = {};
    const materializedMovements = movementsToInsert.flatMap((movement) => {
      const requested = Number(movement.quantity);
      const available = remainingByFeed.get(movement.feedId) ?? 0;
      const actual = Math.min(requested, Math.max(0, available));
      if (actual <= 0) return [];
      remainingByFeed.set(movement.feedId, available - actual);
      actualConsumptionByFeed[movement.feedId] = (actualConsumptionByFeed[movement.feedId] ?? 0) + actual;
      return [{ ...movement, quantity: actual.toFixed(2) }];
    });

    if (materializedMovements.length > 0) {
      await tx.insert(feedMovements).values(materializedMovements as any);
    }

    // 4. Descontar solo el consumo materializado (nunca por debajo de 0).
    for (const feedId of Object.keys(actualConsumptionByFeed)) {
      const nuevo = Math.max(0, remainingByFeed.get(feedId) ?? 0);
      await tx
        .update(feedInventory)
        .set({ currentStock: nuevo.toFixed(2), updatedAt: new Date() })
        .where(eq(feedInventory.id, feedId));
    }

    // Advance even when stock was empty and no consumption row could be
    // written. A replenishment later starts accruing from the next run/day.
    await tx.insert(appSettings).values({ key: FEED_PROGRAM_CHECKPOINT_KEY, value: asOfStr })
      .onConflictDoUpdate({
        target: appSettings.key,
        set: { value: asOfStr, updatedAt: new Date() },
      });
  });
}
