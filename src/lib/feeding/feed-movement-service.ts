import { eq, sql } from "drizzle-orm";
import { db } from "@/db";
import { farmLocations, feedInventory, feedMovements, transactions } from "@/db/schema";
import { ApiHttpError } from "@/lib/api-handler";
import { todayColombiaIso } from "@/lib/date-validation";
import { isPurchasedFeedCategory } from "@/lib/feed-classification";
import { resolveExpenseClassification } from "@/lib/finance/standard-expense-catalog";
import { normalizeFeedingSpecies } from "@/lib/species";
import { runFeedProgramCatchup } from "./runProgram";

export interface RegisterFeedMovementOptions {
  id?: string;
  isOfflineSync?: boolean;
}

export interface RegisterFeedMovementResult {
  inserted: typeof feedMovements.$inferSelect;
  feedName: string;
  feedUnit: string;
  feedCost: string | null;
  resolvedLocationName: string | null;
  deduplicated: boolean;
}

/**
 * Servicio único transaccional para movimientos de alimento (entradas y consumos)
 * invocado por `/api/produccion/alimentacion/movimientos` y `/api/sync/batch`.
 */
export async function registerFeedMovement(
  body: Record<string, any>,
  options: RegisterFeedMovementOptions = {},
): Promise<RegisterFeedMovementResult> {
  const recordId =
    typeof options.id === "string" && options.id.trim()
      ? options.id.trim()
      : typeof body.id === "string" && body.id.trim()
        ? body.id.trim()
        : undefined;

  if (recordId) {
    const [existing] = await db
      .select()
      .from(feedMovements)
      .where(eq(feedMovements.id, recordId));
    if (existing) {
      return {
        inserted: existing,
        feedName: "",
        feedUnit: "",
        feedCost: existing.unitCost,
        resolvedLocationName: null,
        deduplicated: true,
      };
    }
  }

  const qty = Number(body.quantity);
  if (!Number.isFinite(qty) || qty <= 0) {
    throw new ApiHttpError(400, "Cantidad inválida");
  }
  if (typeof body.isEntry !== "boolean") {
    throw new ApiHttpError(400, "Tipo de movimiento inválido");
  }
  if (typeof body.feedId !== "string" || !body.feedId.trim()) {
    throw new ApiHttpError(400, "Alimento requerido");
  }
  if (!body.isEntry && !body.locationId) {
    throw new ApiHttpError(400, "Selecciona el lugar al que se suministró el alimento");
  }

  let resolvedLocationName: string | null = null;
  if (body.locationId) {
    const [location] = await db
      .select({
        id: farmLocations.id,
        name: farmLocations.name,
        status: farmLocations.status,
        operationalStatus: farmLocations.operationalStatus,
      })
      .from(farmLocations)
      .where(eq(farmLocations.id, String(body.locationId)));

    if (
      !location ||
      location.status !== "activa" ||
      (!body.isEntry && ["restringida", "fuera_servicio"].includes(location.operationalStatus))
    ) {
      throw new ApiHttpError(400, "Selecciona un lugar activo y disponible");
    }
    resolvedLocationName = location.name;
  }

  if (
    typeof body.date !== "string" ||
    !/^\d{4}-\d{2}-\d{2}$/.test(body.date) ||
    Number.isNaN(new Date(`${body.date}T00:00:00.000Z`).getTime()) ||
    new Date(`${body.date}T00:00:00.000Z`).toISOString().slice(0, 10) !== body.date
  ) {
    throw new ApiHttpError(400, "Fecha inválida");
  }

  const maxAllowedUtc = new Date().toISOString().slice(0, 10);
  const maxAllowedCo = todayColombiaIso();
  if (body.date > maxAllowedUtc && body.date > maxAllowedCo) {
    throw new ApiHttpError(400, "No se pueden registrar movimientos de alimento en una fecha futura");
  }

  // Materializar consumos pendientes del programa antes de aplicar el movimiento manual
  await runFeedProgramCatchup();

  const created = await db.transaction(async (tx) => {
    const [feed] = await tx
      .select()
      .from(feedInventory)
      .where(eq(feedInventory.id, body.feedId))
      .for("update");

    if (!feed) {
      throw new ApiHttpError(404, "Alimento no encontrado");
    }

    if (!body.isEntry && qty > Number(feed.currentStock)) {
      throw new ApiHttpError(
        400,
        `Stock insuficiente: ${feed.name} solo tiene ${feed.currentStock} ${feed.unit}`,
      );
    }

    const [inserted] = await tx
      .insert(feedMovements)
      .values({
        id: recordId || undefined,
        feedId: body.feedId,
        quantity: String(body.quantity),
        isEntry: body.isEntry,
        movementType: body.movementType || (body.isEntry ? "compra" : "consumo_manual"),
        autoGenerated: false,
        stageCatalogoId: body.stageCatalogoId || null,
        henCount: body.henCount || null,
        species: normalizeFeedingSpecies(body.species),
        unitCost: body.isEntry ? null : feed.costPerUnit,
        locationId: body.locationId || null,
        date: body.date,
        notes: body.notes || null,
      })
      .returning();

    await tx
      .update(feedInventory)
      .set({
        currentStock: body.isEntry
          ? sql`(${feedInventory.currentStock}::numeric + ${qty})`
          : sql`(${feedInventory.currentStock}::numeric - ${qty})`,
        updatedAt: new Date(),
      })
      .where(eq(feedInventory.id, body.feedId));

    if (body.isEntry && isPurchasedFeedCategory(feed.category) && Number(feed.costPerUnit) > 0) {
      const amount = (qty * Number(feed.costPerUnit)).toFixed(2);
      const description = options.isOfflineSync
        ? `Compra de ${body.quantity} ${feed.unit} de ${feed.name} (offline sync)`
        : `Compra de ${body.quantity} ${feed.unit} de ${feed.name}`;
      const resolvedFeedTx = resolveExpenseClassification({
        type: "egreso",
        category: "Compra de alimento",
        sourceType: "alimento",
        description,
      });
      await tx.insert(transactions).values({
        date: body.date,
        type: "egreso",
        category: "Compra de alimento",
        description,
        amount,
        quantity: String(body.quantity),
        unitPrice: feed.costPerUnit,
        unit: feed.unit,
        counterparty: feed.supplier || null,
        sourceType: "alimento",
        sourceId: inserted.id,
        species: body.species || null,
        locationId: body.locationId || null,
        batchId: body.batchId || null,
        expenseCatalogId: resolvedFeedTx.expenseCatalogId,
        expenseFamily: resolvedFeedTx.expenseFamily,
        expenseConcept: resolvedFeedTx.expenseConcept,
        expenseTreatment: resolvedFeedTx.expenseTreatment,
        expenseDriver: resolvedFeedTx.expenseDriver,
      });
    }

    return {
      inserted,
      feedName: feed.name,
      feedUnit: feed.unit,
      feedCost: feed.costPerUnit,
    };
  });

  return {
    ...created,
    resolvedLocationName,
    deduplicated: false,
  };
}
